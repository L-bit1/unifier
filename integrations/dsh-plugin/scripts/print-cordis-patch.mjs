#!/usr/bin/env node
/**
 * Print cordis.yml patch with absolute path to src/index.ts for `dsh web --patch`.
 */
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import fs from 'node:fs'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const pluginTs = path.join(root, 'src', 'index.ts')
const hubUrl = process.env.UNIFIER_HUB_URL || process.env.HUB_URL || 'http://127.0.0.1:8787'
const deviceId = process.env.UNIFIER_DEVICE_ID || process.env.DEVICE_ID || 'mac-a'
const agentId = process.env.UNIFIER_AGENT_ID || 'dsh'

const yaml = `# Generated by npm run print-patch — do not commit if paths differ per machine
- insert:
    - id: unifier
      name: '${pluginTs.replace(/\\/g, '/')}'
      config:
        hubUrl: '${hubUrl}'
        deviceId: '${deviceId}'
        agentId: '${agentId}'
`

const out = path.join(root, 'unifier.cordis.yml')
fs.writeFileSync(out, yaml, 'utf8')
process.stdout.write(`Wrote ${out}\n`)
process.stdout.write(yaml)
